const batchColumns = `id, total, idempotency_key, request_hash, created_at`

func scanBatch(row pgx.Row) (domain.Batch, error) {
	var b domain.Batch
	err := row.Scan(&b.ID, &b.Total, &b.IdempotencyKey, &b.RequestHash, &b.CreatedAt)
	return b, err
}

// GetBatchByIdempotencyKey returns domain.ErrNotFound when no batch was
// created with key.
func (s *Store) GetBatchByIdempotencyKey(ctx context.Context, key string) (domain.Batch, error) {
	b, err := scanBatch(s.pool.QueryRow(ctx,
		`SELECT `+batchColumns+` FROM batches WHERE idempotency_key = $1`, key))
	if errors.Is(err, pgx.ErrNoRows) {
		return domain.Batch{}, domain.ErrNotFound
	}
	if err != nil {
		return domain.Batch{}, fmt.Errorf("load batch by idempotency key: %w", err)
	}
	return b, nil
}

// InsertBatch creates the batch row and all its notifications in one
// transaction: either the whole batch is enqueued or none of it is.
//
// Notifications are written with COPY, which streams all rows in a single
// round trip and is several times faster than a multi-row INSERT for 1000
// rows. IDs are generated by the caller, so COPY's lack of RETURNING does
// not matter.
//
// If the batch's idempotency key already exists, nothing is written and the
// existing batch is returned with created=false.
func (s *Store) InsertBatch(ctx context.Context, b domain.Batch, items []domain.Notification) (domain.Batch, bool, error) {
	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return domain.Batch{}, false, fmt.Errorf("begin: %w", err)
	}
	defer func() { _ = tx.Rollback(ctx) }() // no-op after Commit

	created, err := scanBatch(tx.QueryRow(ctx, `
		INSERT INTO batches (id, total, idempotency_key, request_hash)
		VALUES ($1, $2, $3, $4)
		ON CONFLICT (idempotency_key) DO NOTHING
		RETURNING `+batchColumns,
		b.ID, b.Total, b.IdempotencyKey, b.RequestHash))
	if errors.Is(err, pgx.ErrNoRows) && b.IdempotencyKey != nil {
		// Read committed: this statement sees the row the conflicting
		// transaction committed (ON CONFLICT waited for it).
		existing, err := scanBatch(tx.QueryRow(ctx,
			`SELECT `+batchColumns+` FROM batches WHERE idempotency_key = $1`, *b.IdempotencyKey))
		if err != nil {
			return domain.Batch{}, false, fmt.Errorf("load batch by idempotency key: %w", err)
		}
		return existing, false, nil
	}
	if err != nil {
		return domain.Batch{}, false, fmt.Errorf("insert batch: %w", err)
	}

	// COPY can't use column defaults per row, so immediate rows get the
	// transaction's now() explicitly: the same database clock the claim
	// query uses (see scheduledDueAt).
	var dbNow time.Time
	if err := tx.QueryRow(ctx, `SELECT now()`).Scan(&dbNow); err != nil {
		return domain.Batch{}, false, fmt.Errorf("read database time: %w", err)
	}
	columns := []string{"id", "batch_id", "correlation_id", "trace_parent", "channel", "priority",
		"recipient", "content", "template_id", "variables", "status", "max_attempts",
		"next_attempt_at", "scheduled_at"}
	rows := make([][]any, len(items))
	for i, n := range items {
		due := dbNow
		if at := scheduledDueAt(n); at != nil {
			due = *at
		}
		rows[i] = []any{n.ID, created.ID, n.CorrelationID, n.TraceParent, n.Channel, n.Priority,
			n.Recipient, n.Content, n.TemplateID, n.Variables, n.Status, n.MaxAttempts,
			due, n.ScheduledAt}
	}
	if _, err := tx.CopyFrom(ctx, pgx.Identifier{"notifications"}, columns, pgx.CopyFromRows(rows)); err != nil {
		return domain.Batch{}, false, fmt.Errorf("copy batch notifications: %w", err)
	}

	if err := tx.Commit(ctx); err != nil {
		return domain.Batch{}, false, fmt.Errorf("commit batch: %w", err)
	}
	return created, true, nil
}

// GetBatchSummary returns the batch with live per-status counts. Counts are
// computed on read (GROUP BY over the batch_id index) rather than stored, so
// they can never drift from the notifications themselves.
func (s *Store) GetBatchSummary(ctx context.Context, id uuid.UUID) (domain.BatchSummary, error) {
	b, err := scanBatch(s.pool.QueryRow(ctx, `SELECT `+batchColumns+` FROM batches WHERE id = $1`, id))
	if errors.Is(err, pgx.ErrNoRows) {
		return domain.BatchSummary{}, domain.ErrNotFound
	}
	if err != nil {
		return domain.BatchSummary{}, fmt.Errorf("get batch: %w", err)
	}

	rows, err := s.pool.Query(ctx,
		`SELECT status, count(*) FROM notifications WHERE batch_id = $1 GROUP BY status`, id)
	if err != nil {
		return domain.BatchSummary{}, fmt.Errorf("count batch statuses: %w", err)
	}
	defer rows.Close()

	summary := domain.BatchSummary{Batch: b, StatusCounts: map[domain.Status]int{}}
	for rows.Next() {
		var status domain.Status
		var count int
		if err := rows.Scan(&status, &count); err != nil {
			return domain.BatchSummary{}, fmt.Errorf("scan status count: %w", err)
		}
		summary.StatusCounts[status] = count
	}
	return summary, rows.Err()
}

// ListBatchItems pages through a batch's notifications in creation order.
// All rows of a batch share one created_at (same transaction), so ordering
// effectively falls back to id; UUIDv7 ids are time-ordered and monotonic
// within a process, so id order equals the order of items in the request.
func (s *Store) ListBatchItems(ctx context.Context, batchID uuid.UUID, limit int, after *Cursor) ([]domain.Notification, *Cursor, error) {
	args := []any{batchID, limit + 1}
	query := `SELECT ` + NotificationColumns + ` FROM notifications WHERE batch_id = $1`
	if after != nil {
		args = append(args, after.CreatedAt, after.ID)
		query += ` AND (created_at, id) > ($3, $4)`
	}
	query += ` ORDER BY created_at, id LIMIT $2`

	rows, err := s.pool.Query(ctx, query, args...)
	if err != nil {
		return nil, nil, fmt.Errorf("list batch items: %w", err)
	}
	items, err := collectNotifications(rows)
	if err != nil {
		return nil, nil, fmt.Errorf("list batch items: %w", err)
	}
	items, next := pageOf(items, limit)
	return items, next, nil
}

// ListBatchItemIDs returns every notification id of a batch in request
// order. Used to answer an idempotent replay of a batch create.
func (s *Store) ListBatchItemIDs(ctx context.Context, batchID uuid.UUID) ([]uuid.UUID, error) {
	rows, err := s.pool.Query(ctx,
		`SELECT id FROM notifications WHERE batch_id = $1 ORDER BY created_at, id`, batchID)
	if err != nil {
		return nil, fmt.Errorf("list batch item ids: %w", err)
	}
	ids, err := pgx.CollectRows(rows, pgx.RowTo[uuid.UUID])
	if err != nil {
		return nil, fmt.Errorf("list batch item ids: %w", err)
	}
	return ids, nil
}
